import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

def R(f3, f7, rd, rs1, rs2, op=0x33):
    return (f7 << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op

def I(imm, rd, rs1, f3=0b000, op=0x13):
    return ((imm & 0xFFF) << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op

def S(imm, rs2, rs1, f3=0b010, op=0x23):
    return (((imm >> 5) & 0x7F) << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | ((imm & 0x1F) << 7) | op

def B(imm, rs2, rs1, f3, op=0x63):
    i = imm & 0x1FFF
    return (((i >> 12) & 1) << 31) | (((i >> 5) & 0x3F) << 25) | (rs2 << 20) | (rs1 << 15) \
         | (f3 << 12) | (((i >> 1) & 0xF) << 8) | (((i >> 11) & 1) << 7) | op

def U(imm20, rd, op=0x37):
    return (imm20 << 12) | (rd << 7) | op

def J(imm, rd, op=0x6F):
    i = imm & 0x1FFFFF
    return (((i >> 20) & 1) << 31) | (((i >> 1) & 0x3FF) << 21) | (((i >> 11) & 1) << 20) \
         | (((i >> 12) & 0xFF) << 12) | (rd << 7) | op

# ============================================================
# TB-A: 五级流水基本正确性 + 顺序路径(无冒险)
# ============================================================
tbA = [
    ("lui   x10, 0x12345", U(0x12345, 10)),
    ("auipc x11, 0x1",     U(0x00001, 11, 0x17)),
    ("addi  x12, x0, -1",  I(0xFFF, 12, 0)),
    ("slli  x14, x12, 4",  I(0x004, 14, 12, 0b001)),
    ("srli  x15, x12, 28", I(0x01C, 15, 12, 0b101)),
    ("sw    x14, 8(x0)",   S(8, 14, 0)),
]

# ============================================================
# TB-B: 判决位 (rd==0 / 不同 rd 同时写)
# ============================================================
tbB = [
    ("addi  x1, x0, 0x7FF", I(0x7FF, 1, 0)),     # 0x00  x1 = 2047
    ("addi  x0, x0, 0x123", I(0x123, 0, 0)),     # 0x04  ★ x0 必须保持 0
    ("lui   x2, 0x5",       U(5, 2)),            # 0x08  x2 = 0x5000
    ("lui   x3, 0x5",       U(5, 3)),            # 0x0c  x3 = 0x5000
    ("addi  x4, x0, 0x55",  I(0x055, 4, 0)),     # 0x10  x4 = 0x55
]

# ============================================================
# TB-C: ALU 结果转发 (EX/MEM -> EX) + 连续 RAW 链
# ============================================================
tbC = [
    ("addi  x1, x0, 0x11",  I(0x011, 1, 0)),     # 0x00
    ("addi  x2, x1, 0x01",  I(0x001, 2, 1)),     # 0x04  RAW, dist=1 -> EX/MEM 转发
    ("addi  x3, x2, 0x01",  I(0x001, 3, 2)),     # 0x08  RAW, dist=1
    ("addi  x4, x3, 0x01",  I(0x001, 4, 3)),     # 0x0c  RAW, dist=1
    ("addi  x5, x4, 0x01",  I(0x001, 5, 4)),     # 0x10  RAW, dist=1
    ("slli  x6, x5, 2",     I(0x002, 6, 5, 0b001)),  # 0x14 RAW, dist=1
    ("srli  x7, x6, 1",     I(0x001, 7, 6, 0b101)),  # 0x18 RAW, dist=1
]

# ============================================================
# TB-D: load-use 冒险(必须停 1 拍)
# ============================================================
tbD = [
    ("addi  x1, x0, 0x1F",  I(0x01F, 1, 0)),     # 0x00  x1 = 0x1F  -> 存到 mem[1]
    ("sw    x1, 4(x0)",     S(4, 1, 0)),         # 0x04
    ("lw    x2, 4(x0)",     I(4, 2, 0, 0b010, 0x03)),  # 0x08  load-use(紧邻)
    ("addi  x3, x2, 0x10",  I(0x010, 3, 2)),     # 0x0c  ★ 停 1 拍
    ("lw    x4, 4(x0)",     I(4, 4, 0, 0b010, 0x03)),  # 0x10
    ("lw    x5, 4(x0)",     I(4, 5, 0, 0b010, 0x03)),  # 0x14
    ("addi  x6, x5, 0x02",  I(0x002, 6, 5)),     # 0x18  ★ 停 1 拍
]

# ============================================================
# TB-E: 分支 + 转发(beq 的分支比较吃转发值)
# ============================================================
tbE = [
    ("addi  x1, x0, 0x0A",  I(0x00A, 1, 0)),     # 0x00  x1 = 10
    ("addi  x2, x0, 0x0A",  I(0x00A, 2, 0)),     # 0x04  x2 = 10
    ("beq   x1, x2, +12",   B(12, 2, 1, 0b000)), # 0x08  ★ taken,比较结果吃 EX/MEM 转发
    ("addi  x20, x0, 0x777",I(0x777, 20, 0)),    # 0x0c  错路哨兵
    ("addi  x21, x0, 0x888",I(0x888, 21, 0)),    # 0x10  错路哨兵
    ("addi  x3, x1, 0x01",  I(0x001, 3, 1)),     # 0x14  ★ 分支延迟槽:距离 2,走 MEM/WB 转发
    ("lui   x4, 0x99",      U(0x99, 4)),         # 0x18
]

# ============================================================
# TB-F: 分支 + load-use 相互作用
# ============================================================
tbF = [
    ("addi  x1, x0, 0x33",  I(0x033, 1, 0)),     # 0x00
    ("sw    x1, 4(x0)",     S(4, 1, 0)),         # 0x04
    ("lw    x2, 4(x0)",     I(4, 2, 0, 0b010, 0x03)),  # 0x08
    ("beq   x2, x1, +12",   B(12, 1, 2, 0b000)), # 0x0c  ★ 分支吃 load 结果 -> 停 1 拍后 taken
    ("addi  x20, x0, 0x111",I(0x111, 20, 0)),    # 0x10  错路
    ("addi  x21, x0, 0x222",I(0x222, 21, 0)),    # 0x14  错路
    ("addi  x3, x2, 0x01",  I(0x001, 3, 2)),     # 0x18
]

for name, p in [("A", tbA), ("B", tbB), ("C", tbC), ("D", tbD), ("E", tbE), ("F", tbF)]:
    print("// ===== TB-%s =====" % name)
    for i, (asm, v) in enumerate(p):
        print("mem[%2d] = 32'h%08X;  // 0x%02X  %-22s" % (i, v, i * 4, asm))
    print()

# ============================================================
# TB-G: jal / jalr 跳转 + 链接值 + 错路哨兵
# ============================================================
tbG = [
    ("addi  x1, x0, 0x05",  I(0x005, 1, 0)),     # 0x00  x1 = 5
    ("jal   x2, +12",       J(12, 2)),           # 0x04  → 0x10, link = 0x08
    ("addi  x20, x0, 0x111",I(0x111, 20, 0)),    # 0x08  错路哨兵
    ("addi  x21, x0, 0x222",I(0x222, 21, 0)),    # 0x0C  错路哨兵
    ("addi  x3, x0, 0x07",  I(0x007, 3, 0)),     # 0x10  x3 = 7
    ("jalr  x4, x1, 0x20",  I(0x020, 4, 1, 0b000, 0x67)),  # 0x14 → 5+0x20=0x25, link=0x18
    ("addi  x22, x0, 0x333",I(0x333, 22, 0)),    # 0x18  错路哨兵
    ("addi  x23, x0, 0x444",I(0x444, 23, 0)),    # 0x1C  错路哨兵
    ("addi  x5, x0, 0x09",  I(0x009, 5, 0)),     # 0x20  x5 = 9
    ("addi  x6, x0, 0x0B",  I(0x00B, 6, 0)),     # 0x24  x6 = 0xB  (jalr 目标 0x24 这里)
]
print("// ===== TB-G (jal/jalr) =====")
for i, (asm, v) in enumerate(tbG):
    print("mem[%2d] = 32'h%08X;  // 0x%02X  %-22s" % (i, v, i * 4, asm))
print()

# ============================================================
# TB-H: 分支不命中(顺延)+ 各立即数类型组合
# ============================================================
tbH = [
    ("addi  x1, x0, 0x0A",  I(0x00A, 1, 0)),     # 0x00
    ("addi  x2, x0, 0x14",  I(0x014, 2, 0)),     # 0x04  x2=0x14 != x1
    ("beq   x1, x2, +12",   B(12, 2, 1, 0b000)), # 0x08  NOT taken → 顺延
    ("addi  x3, x0, 0x33",  I(0x033, 3, 0)),     # 0x0C  ★ 应执行
    ("bne   x1, x2, +8",    B(8, 2, 1, 0b001)),  # 0x10  TAKEN → 0x18
    ("addi  x20, x0, 0x555",I(0x555, 20, 0)),    # 0x14  错路
    ("sw    x3, 8(x0)",     S(8, 3, 0)),         # 0x18  store 0x33 到 mem[2]
    ("lw    x4, 8(x0)",     I(8, 4, 0, 0b010, 0x03)),  # 0x1C  x4 = 0x33
]
print("// ===== TB-H (分支不命中 + 访存) =====")
for i, (asm, v) in enumerate(tbH):
    print("mem[%2d] = 32'h%08X;  // 0x%02X  %-22s" % (i, v, i * 4, asm))
print()
