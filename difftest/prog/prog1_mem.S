# =============================================================================
# prog1_mem.S  --  含访存的覆盖测试（差分验证程序 1）
# -----------------------------------------------------------------------------
# 在 prog0 的"运算 + 控制流"基础上加入 load/store 全家族：
#   sw / sh / sb  与  lw / lh / lb / lhu / lbu
#
# 本程序的作用不只是"再跑一遍"：它专门用来暴露**访存路径的时序问题**。
# data_ram 是同步读、1 拍延迟的 IP；如果 load 的写回没有多占一拍，
# 写进 rd 的就是上一个地址的数据 —— 差分比对会在第一条 lw 处精确报错。
#
# 数据基址取 0x40，落在 data_ram 的 4KB 空间内（地址只取 [11:2]）。
# 只做**对齐**访存：本工程的 l_alu 对 offset=01/11 的 lh/lhu 没有正确实现，
# 那属于已知限制，混进来会混淆"时序错"与"译码错"两个问题。
# =============================================================================
        .org 0
_start:
        addi  x1, x0, 0x40          # x1 = 数据基址
        addi  x2, x0, 0x123         # 待写数据

        # ---------------- 字访存 ----------------
        sw    x2, 0(x1)             # mem[0x40] = 0x00000123
        lw    x3, 0(x1)             # 读回
        addi  x4, x3, 1
        sw    x4, 4(x1)
        lw    x5, 4(x1)
        add   x6, x5, x3            # x6 = 0x248

        # ---------------- 字节访存 ----------------
        sb    x2, 8(x1)             # mem[0x48] 低字节 = 0x23
        lb    x7, 8(x1)             # 有符号 -> 0x00000023
        lbu   x8, 8(x1)             # 无符号 -> 0x00000023
        addi  x9, x0, -1
        sb    x9, 9(x1)             # mem[0x48+1] = 0xFF
        lb    x10, 9(x1)            # 有符号 -> 0xFFFFFFFF
        lbu   x11, 9(x1)            # 无符号 -> 0x000000FF
        lw    x12, 8(x1)            # 整字读 -> 0x0000FF23

        # ---------------- 半字访存 ----------------
        addi  x13, x0, -2
        sh    x13, 12(x1)           # mem[0x4C] 低半字 = 0xFFFE
        lh    x14, 12(x1)           # 有符号 -> 0xFFFFFFFE
        lhu   x15, 12(x1)           # 无符号 -> 0x0000FFFE
        sh    x2, 14(x1)            # mem[0x4C] 高半字 = 0x0123
        lw    x16, 12(x1)           # 整字读 -> 0x0123FFFE

        # ---------------- 用 load 结果做控制流（访存->分支的依赖） ----------------
        addi  x17, x0, 10
        addi  x18, x0, 12
_l:
        lw    x19, 0(x1)            # 0x123 = 291
        addi  x17, x17, 1
        blt   x17, x18, _l          # 跑 2 轮，且每轮都依赖 lw 的结果
        sub   x20, x19, x3          # 两次读同一地址，应相等 -> 0

halt:
        jal   x0,  halt
