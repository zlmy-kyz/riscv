# =============================================================================
# prog0_alu.S  --  不访存的覆盖测试（差分验证程序 0）
# -----------------------------------------------------------------------------
# 覆盖：R 型全 10 条 / I 型 6 条 / 移位立即数 3 条 / lui / auipc /
#       6 条分支（命中 + 不命中）/ jal / jalr / 循环 / 背靠背 RAW
# 不含 load/store —— 把"控制流与运算"和"访存路径"分开定位，
# 一旦本程序 PASS，说明前端取指、分支冲刷、译码、ALU、写回这条链是对的。
#
# 约定：程序必须以 "halt: jal x0, halt" 结尾 —— 这是黄金模型与 RTL
#       共同认可的停机标记（自环 jal x0）。两边都在这里收工。
# =============================================================================
        .org 0
_start:
        # ---------------- 算术 / 逻辑 / 移位 / 比较 ----------------
        addi  x1, x0, 10            # x1 = 10
        addi  x2, x0, -3            # x2 = -3（顺带测立即数符号扩展）
        add   x3, x1, x2
        sub   x4, x1, x2
        and   x5, x1, x2
        or    x6, x1, x2
        xor   x7, x1, x2
        sll   x8, x1, x2            # 移位量取 x2 低 5 位
        srl   x9, x2, x1
        sra   x10, x2, x1
        slt   x11, x2, x1           # -3 < 10  -> 1
        sltu  x12, x2, x1           # 无符号比较 -> 0
        slti  x13, x2, 1
        sltiu x14, x2, 1
        andi  x15, x1, 15
        ori   x16, x1, 48
        xori  x17, x1, -1           # 负数立即数
        slli  x18, x1, 3
        srli  x19, x2, 1
        srai  x20, x2, 1
        lui   x21, 0x12345
        auipc x22, 2                # x22 = 本指令 PC + 0x2000
        nop

        # ---------------- 循环：1+2+...+10 ----------------
        # 同时压测"背靠背 RAW"：add -> addi -> blt 三条紧邻、互相依赖
        addi  x5, x0, 0             # 累加器
        addi  x6, x0, 1             # i
        addi  x7, x0, 11            # 上限
_loop:
        add   x5, x5, x6
        addi  x6, x6, 1
        blt   x6, x7, _loop         # 命中 10 次

        # ---------------- 分支：命中 / 不命中成对出现 ----------------
        # 每条分支后面跟一个哨兵 addi：只有"没跳"才会执行，
        # 于是跳与不跳两条路都在写回轨迹里留下痕迹，可被比对器识别。
        beq   x1, x0, _b1           # 不命中
        addi  x23, x0, 0x101
_b1:    beq   x1, x1, _b2           # 命中 -> 跳过哨兵
        addi  x23, x0, 0x102
_b2:    bne   x1, x1, _b3           # 不命中
        addi  x24, x0, 0x201
_b3:    bne   x1, x2, _b4           # 命中
        addi  x24, x0, 0x202
_b4:    blt   x2, x1, _b5           # 命中（有符号）
        addi  x25, x0, 0x301
_b5:    blt   x1, x2, _b6           # 不命中
        addi  x26, x0, 0x401
_b6:    bge   x1, x2, _b7           # 命中
        addi  x26, x0, 0x402
_b7:    bltu  x1, x2, _b8           # 不命中（无符号下 -3 极大）
        addi  x27, x0, 0x501
_b8:    bgeu  x1, x2, _b9           # 命中
        addi  x27, x0, 0x502
_b9:

        # ---------------- jal / jalr ----------------
        jal   x28, _sub1            # 调用子程序，链接值 = 下一条地址
        jal   x0,  _after_sub       # 子程序返回后落在这里，跳过子程序体
_sub1:
        addi  x29, x0, 0x600        # 子程序体
        jalr  x0,  x28, 0           # 返回
_after_sub:
        addi  x30, x0, 0x700

        # ---------------- 用寄存器算目标地址的 jalr ----------------
        addi  x31, x0, _here + 4    # 目标 = _here+4（即下面的 addi x30）
        jalr  x0,  x31, 0
        addi  x30, x0, 0x701        # 被跳过
_here:
        addi  x30, x0, 0x702
        add   x11, x30, x31

        # ---------------- 停机 ----------------
halt:
        jal   x0,  halt             # 自环：黄金模型与 RTL 的停机标记
