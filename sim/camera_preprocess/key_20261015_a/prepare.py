"""Generate the frozen golden facts and the real-CPU image for the key group."""
import argparse, json, subprocess, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import reference as R


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--expect-only', action='store_true')
    a = p.parse_args()
    gen = HERE / 'generated'
    gen.mkdir(exist_ok=True)
    facts = R.frame_facts()
    # Independent cross-check of the RTL address recurrence against the formula.
    for j in R.JOBS:
        rec = R.rtl_address_recurrence(j['buf'])
        want = [R._local(j['buf'], x, y) for y in range(R.OH) for x in range(R.OW)]
        assert rec == want, ('address recurrence', j['job'])
    jobs = [R.job_record(j) for j in R.JOBS]
    soc = [R.job_record(j) for j in R.SOC_JOBS]
    golden = dict(kind='PREPROCESS_96_RGB888', out_bytes=R.OUT_BYTES, out_words=R.OUT_WORDS
                  if hasattr(R, 'OUT_WORDS') else R.OUT_BYTES // 4,
                  out_cpu_base=R.OUT_CPU_BASE, out_native_base=R.OUT_NATIVE_BASE,
                  reads=R.READS, writes=R.WRITES, src_bytes=R.SRC_BYTES,
                  jobs=jobs, soc_jobs=soc, facts=facts,
                  crc='IEEE reflected CRC32 (init ffffffff, poly edb88320, final xor)')
    (gen / 'golden.json').write_text(json.dumps(golden, indent=2) + '\n', encoding='utf-8')
    # Fixed program data for the real-CPU entry (expected values, never from DUT).
    lines = ['/* generated by prepare.py from reference.py; do not edit */',
             '#define PP_NJOBS %d' % len(soc)]
    for name, key, fmt in (('pp_buf', 'buf', '%d'), ('pp_param', 'param', '%d'),
                           ('pp_crc', 'crc32', '0x%08xu'), ('pp_word0', 'word0', '0x%08xu'),
                           ('pp_wordN', 'wordN', '0x%08xu')):
        vals = [fmt % j[key] if '%' in fmt else str(j[key]) for j in soc]
        lines.append('static const unsigned %s[PP_NJOBS] = {%s};' % (name, ','.join(vals)))
    (HERE / 'cpu_sim' / 'expect.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(json.dumps(dict(status='PREPROCESS_GOLDEN_GENERATED_NO_HDL', jobs=len(jobs),
                          soc_jobs=len(soc), golden_sha=None), indent=2))


if __name__ == '__main__':
    main()
